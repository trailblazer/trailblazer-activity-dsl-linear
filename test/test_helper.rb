CU = Trailblazer::Core::Utils
T = Trailblazer::Core

class Minitest::Spec
  include Trailblazer::Core::Utils::AssertEqual
  include Trailblazer::Core::Utils::AssertRun

  def assert_outputs(activity, **tuples)
    outputs = tuples.collect { |semantic, signal| [semantic, Trailblazer::Activity::Output.new(signal, semantic)] }.to_h

    assert_equal activity.to_h[:outputs], outputs
  end

end

module MyTest
  MySuccess = Trailblazer::Activity::Terminus::Success.new(semantic: :success)

  def self.wirings_for_terminus
    Trailblazer::Activity::DSL.wirings_for_terminus(signal: Trailblazer::Activity::Right, semantic: :success)
  end

  def self.options_for_mock_terminus(task: MySuccess, semantic: :success)
    {
      task: task,
      id: :"End.#{semantic}",
      magnetic_to: semantic,
      adds_insertion_args: [:after],
      wirings: {Trailblazer::Activity::Output.new(task, semantic) => Trailblazer::Activity::DSL::Sequence::Search::Nil.new},
    }
  end


  def self.my_options_for_builder(step_normalizer: Trailblazer::Activity::DSL::Normalizer::Step)
    {
      normalizers: {
        step: step_normalizer,
      },
        # sequence: Trailblazer::Activity::DSL::Sequence.new
      default_options: {
        step: {}
      }
    }
  end

  # A minimalistically configured test Topology that uses the pristine Normalizer::Step
  # plus Output() Wiring API.
  def self.my_extended_topology()
    Class.new(Trailblazer::Activity::DSL::Topology) do
      # Since we're in a pure Topology, we don't have any normalizers to extend, yet.
      # This is library-level and won't be needed from any user (I hope :).
      my_builder = Trailblazer::Activity::DSL::Builder.new(
        normalizers: {step: Trailblazer::Activity::DSL::Normalizer::Step}, # the pristine untouched normalizer.
        default_options: Trailblazer::Activity::Path.default_options_for_builder
      )

      activity, builder, helper_forwarder = Trailblazer::Activity::DSL::Topology.build(
        builder: my_builder,
        default_options: {},
        helpers: {
          Trailblazer::Activity::DSL::Feature::OutputTuples::Helper => [:Output, :Id, :Track, :Terminus]
        },
        adds: [
          [
            :normalize_wirings, Trailblazer::Activity::DSL::Feature::OutputTuples::Normalizer::Node,
            :before, :build_task_wrap_node
          ],
        ],
      )

      config.builder = builder
      extend helper_forwarder
    end
  end
end

